#!/usr/bin/env python3
"""
genfont.py - generate uefi/kernel/font8x16.h from a Linux console PSF font.

The Terminus 8x16 console font is used by default.  Debian ships the
compiled console fonts as public-domain data (see console-setup's copyright
file); the header records the source so it can be regenerated.

Usage:
    python3 uefi/tools/genfont.py [FONT.psf|FONT.psf.gz] > uefi/kernel/font8x16.h
"""

import gzip
import struct
import sys
from pathlib import Path

FIRST = 0x20
LAST = 0x7E
DEFAULT_FONTS = [
    "/usr/share/consolefonts/Lat15-Terminus16.psf.gz",
    "/usr/share/consolefonts/Lat15-Terminus16.psf",
    "/usr/share/consolefonts/Lat15-Fixed16.psf.gz",
    "/usr/share/consolefonts/Lat15-Fixed16.psf",
]


def load(path: Path) -> bytes:
    if path.suffix == ".gz":
        with gzip.open(path, "rb") as f:
            return f.read()
    return path.read_bytes()


def parse_psf(data: bytes):
    if data[0:2] == b"\x36\x04":                    # PSF1
        mode = data[2]
        charsize = data[3]
        num_glyphs = 512 if (mode & 1) else 256
        glyph_offset = 4
        has_unicode = bool(mode & 2)
        width = 8
        height = charsize
    elif data[0:4] == b"\x72\xb5\x4a\x86":          # PSF2
        (headersize, flags, num_glyphs, charsize,
         height, width) = struct.unpack_from("<IIIIII", data, 8)
        glyph_offset = headersize
        has_unicode = bool(flags & 1)
    else:
        raise SystemExit("error: not a PSF1/PSF2 font")

    bytes_per_row = (width + 7) // 8
    if bytes_per_row != 1 or height != 16:
        raise SystemExit(f"error: expected 8x16 font, got {width}x{height}")
    if charsize != bytes_per_row * height:
        raise SystemExit("error: unsupported packed PSF glyph size")

    glyphs = data[glyph_offset:glyph_offset + num_glyphs * charsize]
    if len(glyphs) != num_glyphs * charsize:
        raise SystemExit("error: truncated PSF glyph data")

    mapping = {}
    if has_unicode:
        pos = glyph_offset + num_glyphs * charsize
        for glyph_index in range(num_glyphs):
            while pos + 1 < len(data):
                code = struct.unpack_from("<H", data, pos)[0]
                pos += 2
                if code == 0xFFFF:
                    break
                mapping.setdefault(code, glyph_index)
    else:
        for code in range(min(num_glyphs, 256)):
            mapping[code] = code
    return glyphs, charsize, mapping


def main() -> int:
    if len(sys.argv) > 2:
        raise SystemExit("usage: genfont.py [FONT.psf[.gz]]")
    candidates = [Path(sys.argv[1])] if len(sys.argv) == 2 else [Path(p) for p in DEFAULT_FONTS]
    path = next((p for p in candidates if p.exists()), None)
    if path is None:
        raise SystemExit("error: no PSF font found; pass one explicitly")

    data = load(path)
    glyphs, charsize, mapping = parse_psf(data)

    print("/*")
    print(" * font8x16.h - 8x16 bitmap font for the Mini-OS kernel console.")
    print(" *")
    print(f" * Generated by tools/genfont.py from {path.name}.")
    print(" * Rows are one byte each, most significant bit is the leftmost pixel.")
    print(" * Codes 0x20..0x7e are stored; index with (ch - 0x20).")
    print(" *")
    print(" * The Debian console-setup package ships these compiled console fonts")
    print(" * as public-domain data.  Do not edit by hand: rerun the generator.")
    print(" */")
    print("#ifndef MINIOS_FONT8X16_H")
    print("#define MINIOS_FONT8X16_H")
    print()
    print("static const unsigned char font8x16[95][16] = {")
    for code in range(FIRST, LAST + 1):
        glyph_index = mapping.get(code)
        if glyph_index is None:
            raise SystemExit(f"error: font has no glyph for U+{code:04X}")
        base = glyph_index * charsize
        rows = glyphs[base:base + charsize]
        values = ", ".join(f"0x{b:02x}" for b in rows)
        print(f"    {{ {values} }}, /* U+{code:04X} */")
    print("};")
    print()
    print("#endif /* MINIOS_FONT8X16_H */")
    return 0


if __name__ == "__main__":
    sys.exit(main())
